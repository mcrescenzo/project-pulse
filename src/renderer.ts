import type { Feature, Milestone, PulseConfig } from "./types";

function compareAscii(a: string, b: string): number {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

/**
 * Deterministically sorts milestones by numeric `order` ascending, then `id`.
 */
export function sortMilestones(milestones: Milestone[]): Milestone[] {
  return [...milestones].sort((a, b) => {
    const orderDiff = a.order - b.order;
    if (orderDiff !== 0) return orderDiff;
    return compareAscii(a.id, b.id);
  });
}

/**
 * Deterministically sorts features by numeric `order` ascending, then `id`.
 */
export function sortFeatures(features: Feature[]): Feature[] {
  return [...features].sort((a, b) => {
    const orderDiff = a.order - b.order;
    if (orderDiff !== 0) return orderDiff;
    return compareAscii(a.id, b.id);
  });
}

function renderFeatureSection(feature: Feature): string[] {
  const lines: string[] = [];
  lines.push(`### ${feature.title} (\`${feature.id}\`)`);
  lines.push("");

  const meta: string[] = [`**Status:** \`${feature.status}\``];
  if (feature.area) {
    meta.push(`**Area:** ${feature.area}`);
  }
  if (feature.depends_on.length > 0) {
    meta.push(`**Depends on:** ${feature.depends_on.map((d) => `\`${d}\``).join(", ")}`);
  }
  if (feature.refs.length > 0) {
    meta.push(`**Refs:** ${feature.refs.map((r) => `\`${r}\``).join(", ")}`);
  }
  lines.push(meta.join(" | "));
  lines.push("");

  if (feature.description.trim()) {
    lines.push(feature.description.trim());
    lines.push("");
  }

  if (feature.ship_criteria.length > 0) {
    const doneCount = feature.ship_criteria.filter((c) => c.done).length;
    lines.push(`**Ship Criteria (${doneCount}/${feature.ship_criteria.length}):**`);
    for (const criterion of feature.ship_criteria) {
      lines.push(`- [${criterion.done ? "x" : " "}] ${criterion.text}`);
    }
    lines.push("");
  }

  if (feature.updates.length > 0) {
    const latest = feature.updates[feature.updates.length - 1]!;
    lines.push(`> **Latest Pulse (${latest.at}):** ${latest.note}`);
    lines.push("");
  }

  return lines;
}

/**
 * Compiles `.project-pulse/` entities into a deterministic root `ROADMAP.md`.
 */
export function renderRoadmapMarkdown(
  config: PulseConfig,
  milestones: Milestone[],
  features: Feature[]
): string {
  const sortedMilestones = sortMilestones(milestones);
  const sortedFeatures = sortFeatures(features);

  const lines: string[] = [
    "<!-- Auto-generated by project-pulse (pp). Do not edit manually. -->",
    "",
    `# ${config.project.name} — Roadmap`,
    "",
  ];

  if (config.project.summary.trim()) {
    lines.push(config.project.summary.trim());
    lines.push("");
  }

  const featuresByMilestone = new Map<string, Feature[]>();
  for (const feature of sortedFeatures) {
    const list = featuresByMilestone.get(feature.milestone) ?? [];
    list.push(feature);
    featuresByMilestone.set(feature.milestone, list);
  }

  const knownMilestoneIds = new Set(sortedMilestones.map((m) => m.id));

  if (sortedMilestones.length === 0 && sortedFeatures.length === 0) {
    lines.push("_No milestones or features defined yet. Run `pp milestone add` or `pp feature add` to begin._");
    lines.push("");
    return `${lines.join("\n").trimEnd()}\n`;
  }

  for (const milestone of sortedMilestones) {
    lines.push(`## ${milestone.title} (\`${milestone.id}\`)`);
    lines.push("");
    const meta = [`**Status:** \`${milestone.status}\``];
    if (milestone.target) {
      meta.push(`**Target:** ${milestone.target}`);
    }
    const milestoneFeatures = featuresByMilestone.get(milestone.id) ?? [];
    const shippedCount = milestoneFeatures.filter((f) => f.status === "shipped").length;
    meta.push(`**Progress:** ${shippedCount}/${milestoneFeatures.length} features shipped`);
    lines.push(meta.join(" | "));
    lines.push("");

    if (milestone.description.trim()) {
      lines.push(milestone.description.trim());
      lines.push("");
    }

    if (milestoneFeatures.length === 0) {
      lines.push("_No features assigned to this milestone yet._");
      lines.push("");
    } else {
      for (const feature of milestoneFeatures) {
        lines.push(...renderFeatureSection(feature));
      }
    }
  }

  const defaultMilestoneId = config.defaults.milestone;
  if (!knownMilestoneIds.has(defaultMilestoneId)) {
    const backlogFeatures = featuresByMilestone.get(defaultMilestoneId) ?? [];
    if (backlogFeatures.length > 0) {
      lines.push(`## Backlog (\`${defaultMilestoneId}\`)`);
      lines.push("");
      for (const feature of backlogFeatures) {
        lines.push(...renderFeatureSection(feature));
      }
    }
  }

  const orphanFeatures = sortedFeatures.filter(
    (f) => !knownMilestoneIds.has(f.milestone) && f.milestone !== defaultMilestoneId
  );
  if (orphanFeatures.length > 0) {
    lines.push("## Unassigned");
    lines.push("");
    for (const feature of orphanFeatures) {
      lines.push(...renderFeatureSection(feature));
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}
