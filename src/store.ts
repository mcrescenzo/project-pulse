/**
 * Walks up parent directories from `startDir` looking for `.project-pulse/config.yaml`.
 */
export function findProjectRoot(startDir: string): string | null {
  let current = resolve(startDir);
  while (true) {
    if (existsSync(join(current, PULSE_DIR_NAME, CONFIG_FILE_NAME))) {
      return current;
    }
    const parent = dirname(current);
    if (parent === current) {
      return null;
    }
    current = parent;
  }
}

function assertValidId(id: string, kind: string): void {
  if (!id || !VALID_ID_RE.test(id)) {
    throw new Error(
      `Invalid ${kind} id '${id}'. IDs must match /^[a-zA-Z0-9][a-zA-Z0-9._-]*$/`
    );
  }
}

/** The exact first line `renderRoadmapMarkdown` emits for generated roadmaps. */
const GENERATED_ROADMAP_HEADER = `${ROADMAP_GENERATED_MARKER} Do not edit manually. -->`;

/**
 * True only when `content` opens with the exact generated header line. A marker quoted inside a
 * hand-written body (or mid-line) does not make a document generated.
 */
export function isGeneratedRoadmapContent(content: string): boolean {
  for (const line of content.split(/\r?\n/)) {
    if (line.trim() === "") continue;
    return line.trim() === GENERATED_ROADMAP_HEADER;
  }
  return false;
}

function readInitInput(path: string): Buffer | undefined {
  try {
    return readFileSync(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
}

/**
 * Returns the directory entry that writing `fileName` would clobber on a case-insensitive
 * filesystem (an existing sibling differing only by case), or null when the write is safe.
 * An exact entry means the write targets that file itself — case-insensitivity is moot, since
 * both spellings can never coexist as entries on a case-insensitive filesystem. Otherwise a
 * differently-cased sibling plus a resolvable exact path means the filesystem treats both
 * spellings as one file; on a case-sensitive filesystem the exact path is a new distinct file
 * and differently-cased IDs may keep coexisting.
 */
export function caseCollisionEntry(
  entries: string[],
  fileName: string,
  targetExists: boolean
): string | null {
  if (entries.includes(fileName)) return null;
  const lower = fileName.toLowerCase();
  const differing = entries.find((entry) => entry.toLowerCase() === lower);
  if (differing === undefined || !targetExists) return null;
  return differing;
}

function slugifyCriterionId(text: string, usedIds: Set<string>, index: number): string {
  const base = text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .split("-")
    .slice(0, 4)
    .join("-")
    .slice(0, 32);
  let candidate = base || `c-${index + 1}`;
  // Never generate a numeric-only id (pp-f7m.12): UI clients address criteria by id, and the
  // CLI treats digit-only selectors as 1-based positions, so "1" from text like "≤1%" would
  // make clicks and commands hit the wrong checkbox.
  if (NUMERIC_SELECTOR_RE.test(candidate)) {
    candidate = `c-${candidate}`;
  }
  if (!usedIds.has(candidate)) {
    usedIds.add(candidate);
    return candidate;
  }
  let suffix = 2;
  while (usedIds.has(`${candidate}-${suffix}`)) {
    suffix++;
  }
  const unique = `${candidate}-${suffix}`;
  usedIds.add(unique);
  return unique;
}

function normalizeCriteriaInput(
  items: ShipCriterionInput[] | undefined
): ShipCriterion[] {
  if (!items) return [];
  const usedIds = new Set<string>();
  const result: ShipCriterion[] = [];
  for (let i = 0; i < items.length; i++) {
    const item = items[i]!;
    const text = (typeof item === "string" ? item : item.text).trim();
    if (!text) {
      throw new Error(
        `Ship criterion at position ${i + 1} has blank text; criterion text must be non-empty`
      );
    }
    let id: string;
    if (typeof item === "string") {
      id = slugifyCriterionId(text, usedIds, i);
    } else {
      const explicit = item.id?.trim();
      if (explicit) {
        if (NUMERIC_SELECTOR_RE.test(explicit)) {
          throw new Error(
            `Ship criterion id '${explicit}' is numeric; digit-only selectors mean 1-based ` +
              `positions, so criterion ids must contain at least one non-digit character`
          );
        }
        if (usedIds.has(explicit)) {
          throw new Error(
            `Duplicate ship criterion id '${explicit}' at position ${i + 1}; criterion ids must be unique`
          );
        }
        id = explicit;
      } else {
        id = slugifyCriterionId(text, usedIds, i);
      }
    }
    usedIds.add(id);
    result.push({ id, text, done: typeof item === "object" && Boolean(item.done) });
  }
  return result;
}

function nextOrder(items: Array<{ order: number }>): number {
  if (items.length === 0) return 10;
  return Math.max(...items.map((i) => i.order)) + 10;
}

function dedupeStrings(values: string[]): string[] {
  return [...new Set(values.map((v) => v.trim()).filter(Boolean))];
}

/** Human-readable type name for diagnostics; names null and lists instead of "object". */
function describeValueType(value: unknown): string {
  return value === null ? "null" : Array.isArray(value) ? "list" : typeof value;
}

function asStringArray(
  value: unknown,
  field: "depends_on" | "refs",
  featureId: string,
  parseIssues: ValidationIssue[]
): string[] {
  if (value === undefined || value === null) return [];
  const code = field === "depends_on" ? "INVALID_DEPENDS_ON" : "INVALID_REFS";
  if (!Array.isArray(value)) {
    parseIssues.push({
      level: "error",
      code,
      entityId: featureId,
      message: `Feature '${featureId}' ${field} must be a list of strings (got ${describeValueType(value)})`,
    });
    return [];
  }
  const result: string[] = [];
  for (let i = 0; i < value.length; i++) {
    const item = value[i];
    if (typeof item !== "string") {
      parseIssues.push({
        level: "error",
        code,
        entityId: featureId,
        message: `Feature '${featureId}' ${field}[${i}] must be a string (got ${describeValueType(item)})`,
      });
      continue;
    }
    result.push(item);
  }
  return result;
}

function parseShipCriteria(
  value: unknown,
  featureId: string,
  parseIssues: ValidationIssue[]
): ShipCriterion[] {
  if (value === undefined || value === null) return [];
  if (!Array.isArray(value)) {
    parseIssues.push({
      level: "error",
      code: "INVALID_SHIP_CRITERIA",
      entityId: featureId,
      message: `Feature '${featureId}' ship_criteria must be a list`,
    });
    return [];
  }
  // Pass 1: validate shapes, diagnose duplicate canonical ids, and decide which entries keep
  // their stored id versus need a display alias.
  const entries: Array<{ id: string | null; text: string; done: boolean }> = [];
  const seenIds = new Map<string, number>();
  for (let i = 0; i < value.length; i++) {
    const raw = value[i];
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      parseIssues.push({
        level: "error",
        code: "INVALID_SHIP_CRITERIA",
        entityId: featureId,
        message: `Feature '${featureId}' ship_criteria[${i}] must be an object`,
      });
      continue;
    }
    const obj = raw as Record<string, unknown>;
    const rawId = obj.id;
    let id: string | null = null;
    let canonical: string | null = null;
    if (typeof rawId === "string") {
      const trimmed = rawId.trim();
      canonical = trimmed === "" ? null : trimmed;
      id = trimmed !== "" && !NUMERIC_SELECTOR_RE.test(trimmed) ? trimmed : null;
    } else if (typeof rawId === "number" && Number.isFinite(rawId)) {
      canonical = String(rawId);
      id = NUMERIC_SELECTOR_RE.test(canonical) ? null : canonical;
    } else if (rawId !== undefined && rawId !== null) {
      parseIssues.push({
        level: "error",
        code: "INVALID_SHIP_CRITERIA",
        entityId: featureId,
        message: `Feature '${featureId}' ship_criteria[${i}] id must be a string (got ${describeValueType(rawId)})`,
      });
    }
    if (canonical) {
      const firstAt = seenIds.get(canonical);
      if (firstAt === undefined) {
        seenIds.set(canonical, i);
      } else {
        parseIssues.push({
          level: "error",
          code: "DUPLICATE_SHIP_CRITERION_ID",
          entityId: featureId,
          message: `Feature '${featureId}' ship_criteria entries ${firstAt + 1} and ${i + 1} share id '${canonical}'; criterion ids must be unique so checkbox selection is unambiguous`,
        });
      }
    }
    const text = typeof obj.text === "string" ? obj.text : "";
    if (!text.trim()) {
      parseIssues.push({
        level: "error",
        code: "INVALID_SHIP_CRITERIA",
        entityId: featureId,
        message: `Feature '${featureId}' ship_criteria[${i}] text must be a non-empty string`,
      });
    }
    if (obj.done !== undefined && obj.done !== null && typeof obj.done !== "boolean") {
      parseIssues.push({
        level: "error",
        code: "INVALID_SHIP_CRITERIA",
        entityId: featureId,
        message: `Feature '${featureId}' ship_criteria[${i}] done must be a boolean (got ${describeValueType(obj.done)})`,
      });
    }
    entries.push({ id, text, done: obj.done === true });
  }

  // Pass 2: reserve every stored non-numeric id, then give digit-only (legacy) and missing ids
  // deterministic, collision-free display aliases. A UNIQUE numeric id is normalized silently —
  // never a fatal issue, so the store stays mutable and the user can unstick it via the CLI —
  // and the alias is persisted over the stored canonical on that feature's next mutation.
  const usedIds = new Set<string>();
  for (const entry of entries) {
    if (entry.id !== null) usedIds.add(entry.id);
  }
  const result: ShipCriterion[] = [];
  for (let i = 0; i < entries.length; i++) {
    const entry = entries[i]!;
    let id = entry.id;
    if (id === null) {
      id = `c-${i + 1}`;
      let suffix = 2;
      while (usedIds.has(id)) {
        id = `c-${i + 1}-${suffix}`;
        suffix++;
      }
    }
    usedIds.add(id);
    result.push({ id, text: entry.text, done: entry.done });
  }
  return result;
}

function parseUpdates(
  value: unknown,
  featureId: string,
  parseIssues: ValidationIssue[]
): FeatureUpdate[] {
  if (value === undefined || value === null) return [];
  if (!Array.isArray(value)) {
    parseIssues.push({
      level: "error",
      code: "INVALID_UPDATES",
      entityId: featureId,
      message: `Feature '${featureId}' updates must be a list`,
    });
    return [];
  }
  const result: FeatureUpdate[] = [];
  for (let i = 0; i < value.length; i++) {
    const raw = value[i];
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
      parseIssues.push({
        level: "error",
        code: "INVALID_UPDATES",
        entityId: featureId,
        message: `Feature '${featureId}' updates[${i}] must be an object`,
      });
      continue;
    }
    const obj = raw as Record<string, unknown>;
    result.push({
      at: typeof obj.at === "string" ? obj.at : "",
      note: typeof obj.note === "string" ? obj.note : "",
    });
  }
  return result;
}

/**
 * Undo state for a multi-file mutation (pp-f7m.26). `snapshots` are recorded only after a
 * dependent file was successfully overwritten, so rollback never rewrites an unchanged target;
 * `staged` entries are entity files moved aside instead of unlinked, so a failure renames them
 * back without losing symlinks or file permissions.
 */
interface MutationUndo {
  snapshots: Array<{ path: string; previous: string }>;
  staged: Array<{ originalPath: string; stagedPath: string }>;
}

