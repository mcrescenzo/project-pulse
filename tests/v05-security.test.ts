import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import {
  chmodSync,
  lstatSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { CliBeadsClient } from "../src/beads";
import { buildDigest } from "../src/digest";
import { writeFileAtomic } from "../src/frontmatter";
import {
  buildOpenUrl,
  isSafeLocalUrl,
  loadOrCreateAccessToken,
  redactPaths,
  tokensEqual,
} from "../src/http-security";
import { RoadmapService } from "../src/store";

let tempDir: string;

beforeEach(() => {
  tempDir = mkdtempSync(join(tmpdir(), "project-pulse-v05-sec-"));
});

afterEach(() => {
  rmSync(tempDir, { recursive: true, force: true });
});

describe("v0.5 public release security hardening", () => {
  test("writeFileAtomic preserves symlinks and existing permission bits", () => {
    const real = join(tempDir, "CLAUDE.md");
    const link = join(tempDir, "AGENTS.md");
    writeFileSync(real, "original\n");
    symlinkSync("CLAUDE.md", link);

    writeFileAtomic(link, "updated via link\n");
    expect(lstatSync(link).isSymbolicLink()).toBe(true);
    expect(readlinkSync(link)).toBe("CLAUDE.md");
    expect(readFileSync(real, "utf8")).toBe("updated via link\n");

    const secret = join(tempDir, "mcp.json");
    writeFileSync(secret, "{}\n");
    chmodSync(secret, 0o600);
    writeFileAtomic(secret, '{"mcpServers":{}}\n');
    expect(statSync(secret).mode & 0o777).toBe(0o600);

    const fresh = join(tempDir, "fresh.json");
    writeFileAtomic(fresh, "{}\n", { mode: 0o600 });
    expect(statSync(fresh).mode & 0o777).toBe(0o600);
  });

  test("pp init refuses to overwrite a hand-written ROADMAP.md unless forced", () => {
    const roadmapPath = join(tempDir, "ROADMAP.md");
    writeFileSync(roadmapPath, "# My hand-written roadmap\n");
    const svc = new RoadmapService(tempDir);

    expect(() => svc.init({ name: "Guarded" })).toThrow(/not generated by project-pulse/);
    expect(readFileSync(roadmapPath, "utf8")).toBe("# My hand-written roadmap\n");
    expect(svc.isInitialized()).toBe(false);

    svc.init({ name: "Guarded", force: true });
    expect(readFileSync(roadmapPath, "utf8")).toContain("Auto-generated by project-pulse");

    // Re-running init on an already generated roadmap stays allowed
    svc.init({ name: "Guarded" });
  });

  test("access token helpers: persistent 0600 token, constant-time compare, safe open URLs", () => {
    const stateDir = join(tempDir, "state");
    const token = loadOrCreateAccessToken(stateDir);
    expect(token).toMatch(/^[0-9a-f]{64}$/);
    expect(loadOrCreateAccessToken(stateDir)).toBe(token);
    expect(statSync(join(stateDir, "access-token")).mode & 0o777).toBe(0o600);
    expect(statSync(stateDir).mode & 0o777).toBe(0o700);

    expect(tokensEqual(token, token)).toBe(true);
    expect(tokensEqual("short", token)).toBe(false);
    expect(tokensEqual(null, token)).toBe(false);

    expect(buildOpenUrl("http://127.0.0.1:4310", "/p/my-repo", "abc")).toBe(
      "http://127.0.0.1:4310/p/my-repo?t=abc"
    );
    expect(isSafeLocalUrl("http://127.0.0.1:4310/p/x?t=1")).toBe(true);
    expect(isSafeLocalUrl("http://localhost:4310/")).toBe(true);
    expect(isSafeLocalUrl("file:///etc/passwd")).toBe(false);
    expect(isSafeLocalUrl("https://evil.example/")).toBe(false);
    expect(isSafeLocalUrl("http://evil.example:4310/")).toBe(false);
    expect(isSafeLocalUrl("--help")).toBe(false);
    expect(isSafeLocalUrl("http://127.0.0.1:4310/&calc.exe")).toBe(true); // no shell is ever involved

    const home = process.env.HOME ?? "";
    if (home && home !== "/") {
      expect(redactPaths(`not initialized in ${home}/code/repo`)).toBe("not initialized in ~/code/repo");
    }
  });

  test("MCP server answers malformed JSON-RPC messages with -32600 and keeps serving", async () => {
    new RoadmapService(tempDir).init({ name: "MCP Robustness" });
    const lines = [
      "null",
      "42",
      JSON.stringify({ jsonrpc: "2.0", id: 7 }),
      JSON.stringify({ jsonrpc: "2.0", id: 8, method: 123 }),
      JSON.stringify({ jsonrpc: "2.0", id: 9, method: "tools/list" }),
    ];
    const proc = Bun.spawn(
      [process.execPath, "run", join(import.meta.dir, "../src/cli.ts"), "mcp", "--root", tempDir],
      { stdin: new Blob([`${lines.join("\n")}\n`]), stdout: "pipe", stderr: "pipe" }
    );
    const [stdout, code] = await Promise.all([new Response(proc.stdout).text(), proc.exited]);
    expect(code).toBe(0);
    const responses = stdout
      .trim()
      .split("\n")
      .map((l) => JSON.parse(l) as { id: unknown; error?: { code: number }; result?: unknown });
    expect(responses.slice(0, 4).map((r) => r.error?.code)).toEqual([-32600, -32600, -32600, -32600]);
    expect(responses[2]!.id).toBe(7);
    expect(responses[4]!.id).toBe(9);
    expect(responses[4]!.result).toBeDefined();
  });

  test("git refs and Beads ids that look like flags are never parsed as options", async () => {
    const svc = new RoadmapService(tempDir);
    svc.init({ name: "Flag Safety" });
    Bun.spawnSync(["git", "init", "-q"], { cwd: tempDir });
    expect(() => buildDigest(tempDir, { since: "--output=/tmp/pp-should-not-exist" })).toThrow(
      /Could not resolve git ref/
    );

    // Fake bd that records its argv; ids must follow a `--` separator
    const argvLog = join(tempDir, "argv.log");
    const fakeBd = join(tempDir, "fake-bd.sh");
    writeFileSync(fakeBd, `#!/usr/bin/env bash\nprintf '%s\\n' "$@" > "${argvLog}"\necho '[]'\n`);
    chmodSync(fakeBd, 0o755);
    await new CliBeadsClient({ bdBin: fakeBd }).resolveRefs(["bd:--version"], tempDir);
    const argv = readFileSync(argvLog, "utf8").trim().split("\n");
    expect(argv).toEqual(["--readonly", "show", "--json", "--", "--version"]);
  });
});
